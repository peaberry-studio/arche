function packed(rows: string): boolean[] {
  const dots: Array<[number, number]> = []
  rows.split('|').forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] === '#') dots.push([x, y])
    }
  })
  return createFrame(BITMAP_GRID_COLS, BITMAP_GRID_ROWS, dots)
}

function glyph(intervalMs: number, ...frames: string[]): BitmapAnimationConfig {
  return {
    intervalMs,
    frames: frames.map(packed),
  }
}

